#!/usr/bin/env node
// Writes public/.htaccess for Apache (cPanel) hosting:
//  - HTTPS and www canonical host
//  - 301 redirects from every old wiki URL to its new home
//  - 410 Gone for every other old wiki URL (the spam pages), so search
//    engines drop them quickly instead of retrying a 404 for months
//  - caching and a few safe security headers
// Runs automatically before `npm run build`.

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const redirectsFile = join(ROOT, 'src/data/redirects.json');
const redirects = existsSync(redirectsFile) ? JSON.parse(readFileSync(redirectsFile, 'utf8')) : {};

const escRe = (s) => s.replace(/[.*+?^${}()|[\]\\/]/g, '\\$&').replace(/ /g, '_');
// MediaWiki puts titles in query strings URL-encoded, so match that form.
const qsForm = (title) =>
  encodeURIComponent(title.replace(/ /g, '_')).replace(/%3A/gi, ':').replace(/%2F/gi, '/');
const escQs = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

const pathRules = [];
const queryRules = [];
const ORIGIN = 'https://www.projecthomelab.org';
for (const [title, rel] of Object.entries(redirects).sort(([a], [b]) => a.localeCompare(b))) {
  if (title === 'Main Page') continue; // handled below
  const target = rel.startsWith('/') ? ORIGIN + rel : rel;
  pathRules.push(`RewriteRule ^wiki/${escRe(title)}/?$ ${target} [R=301,L,NE]`);
  queryRules.push(
    `RewriteCond %{QUERY_STRING} (^|&)title=${escQs(qsForm(title))}(&|$) [NC]\nRewriteRule ^index\\.php$ ${target.split('#')[0]}${target.includes('?') ? '' : '?'} [R=301,L,NE]`,
  );
}

const out = `# Generated by scripts/build-htaccess.mjs. Edit that script, not this file.
Options -Indexes
DirectoryIndex index.html
ErrorDocument 404 /404.html

<IfModule mod_rewrite.c>
RewriteEngine On

# Canonical address: https://www.projecthomelab.org
RewriteCond %{HTTPS} !=on
RewriteCond %{HTTP:X-Forwarded-Proto} !https
RewriteRule ^ https://www.projecthomelab.org%{REQUEST_URI} [R=301,L,NE]
RewriteCond %{HTTP_HOST} ^projecthomelab\\.org$ [NC]
RewriteRule ^ https://www.projecthomelab.org%{REQUEST_URI} [R=301,L,NE]

# Old wiki home page
RewriteRule ^wiki/?$ https://www.projecthomelab.org/ [R=301,L]
RewriteRule ^wiki/Main_Page/?$ https://www.projecthomelab.org/ [R=301,L]
RewriteCond %{QUERY_STRING} (^|&)title=Main_Page(&|$) [NC]
RewriteRule ^index\\.php$ https://www.projecthomelab.org/? [R=301,L]

# Old wiki articles that moved (/wiki/Title)
${pathRules.join('\n')}

# Old wiki articles that moved (/index.php?title=Title)
${queryRules.join('\n')}

# Everything else from the old wiki is gone for good: spam pages, user
# pages, talk pages, special pages and the MediaWiki engine itself.
RewriteRule ^wiki(/.*)?$ - [G,L]
RewriteRule ^(index|api|load|opensearch_desc|rest|thumb|img_auth)\\.php$ - [G,L]
RewriteRule ^(mw-config|maintenance|skins|extensions|resources|vendor|includes|languages|cache)(/.*)?$ - [G,L]
</IfModule>

<IfModule mod_headers.c>
Header always set X-Content-Type-Options "nosniff"
Header always set Referrer-Policy "strict-origin-when-cross-origin"
Header always set X-Frame-Options "SAMEORIGIN"
Header always set Permissions-Policy "camera=(), microphone=(), geolocation=()"
<FilesMatch "\\.(html)$">
  Header set Cache-Control "public, max-age=600"
</FilesMatch>
# Astro fingerprints everything in /_astro/, so it can be cached forever.
<If "%{REQUEST_URI} =~ m#^/_astro/#">
  Header set Cache-Control "public, max-age=31536000, immutable"
</If>
</IfModule>

<IfModule mod_expires.c>
ExpiresActive On
ExpiresByType image/png "access plus 1 month"
ExpiresByType image/jpeg "access plus 1 month"
ExpiresByType image/gif "access plus 1 month"
ExpiresByType image/svg+xml "access plus 1 month"
ExpiresByType font/woff2 "access plus 1 year"
</IfModule>

<IfModule mod_deflate.c>
AddOutputFilterByType DEFLATE text/html text/css text/plain application/javascript application/json image/svg+xml application/xml
</IfModule>
`;

writeFileSync(join(ROOT, 'public/.htaccess'), out);
console.log(`Wrote public/.htaccess with ${pathRules.length} redirects.`);
